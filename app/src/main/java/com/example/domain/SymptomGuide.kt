    /** Guide for a stored symptom name; also matches older stored names such as "دل‌پیچه و درد شکم". */
    fun forSymptom(name: String): Entry? {
        val key = name.trim()
        ENTRIES[key]?.let { return it }
        return ENTRIES.entries.firstOrNull { key.contains(it.key) || it.key.contains(key) && key.length >= 3 }?.value
    }

    val coveredSymptoms: Set<String> get() = ENTRIES.keys
