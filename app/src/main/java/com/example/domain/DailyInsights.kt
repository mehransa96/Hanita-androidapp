package com.example.domain

/**
 * Builds the "بینش امروز" card: one headline for the state of the cycle plus three practical tips
 * (body, nutrition, mind). Each state has a pool of evidence-based tips and the day of the cycle picks
 * which one is shown, so the card changes from day to day instead of repeating one sentence all phase.
 *
 * Pure Kotlin so it can be unit tested without Android.
 */
object DailyInsights {

    enum class State { NO_DATA, LATE, PERIOD_EARLY, PERIOD_LATE, FOLLICULAR, FERTILE, LUTEAL, PMS }

    data class Tip(val label: String, val text: String)

    data class Insight(val state: State, val headline: String, val tips: List<Tip>, val caution: String?)

    fun stateOf(
        hasData: Boolean,
        isLate: Boolean,
        isPeriod: Boolean,
        isFertile: Boolean,
        isPms: Boolean,
        phase: CyclePredictor.Phase,
        currentDay: Int
    ): State = when {
        !hasData -> State.NO_DATA
        isLate -> State.LATE
        isPeriod -> if (currentDay <= 2) State.PERIOD_EARLY else State.PERIOD_LATE
        isFertile -> State.FERTILE
        isPms -> State.PMS
        phase == CyclePredictor.Phase.MENSTRUAL -> State.PERIOD_LATE
        phase == CyclePredictor.Phase.FOLLICULAR -> State.FOLLICULAR
        phase == CyclePredictor.Phase.OVULATION -> State.FERTILE
        else -> State.LUTEAL
    }

    fun build(state: State, currentDay: Int, daysLate: Int = 0): Insight {
        val day = currentDay.coerceAtLeast(1)
        fun pick(pool: List<String>) = pool[(day - 1) % pool.size]
        val pools = POOLS.getValue(state)
        val headline = if (state == State.LATE) {
            "پریود شما ${com.example.utils.PersianNumbers.toPersianDigits(daysLate)} روز تأخیر دارد. " + HEADLINES.getValue(state)
        } else HEADLINES.getValue(state)
        return Insight(
            state = state,
            headline = headline,
            tips = listOf(
                Tip("بدن", pick(pools.body)),
                Tip("تغذیه", pick(pools.food)),
                Tip("ذهن", pick(pools.mind))
            ),
            caution = CAUTIONS[state]
        )
    }

