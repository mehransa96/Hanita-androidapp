    data class PhaseGuide(
        val focus: String,
        val doThis: List<String>,
        val avoid: List<String>,
        val conflict: String
    )

    fun phaseGuide(phase: Phase): PhaseGuide = when (phase) {
        Phase.PERIOD -> PhaseGuide(
            "آرامش و مراقبت",
            listOf(
                "کارهای خانه و خرید را خودت انجام بده.",
                "کیسه آب گرم، دمنوش و غذای گرم و سبک آماده کن.",
                "برنامه‌ها را سبک کن و به استراحتش احترام بگذار."
