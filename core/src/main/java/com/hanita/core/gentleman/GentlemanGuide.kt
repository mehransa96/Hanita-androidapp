                "شروع بحث سنگین یا تصمیم بزرگ.",
                "گله از کم‌حوصلگی یا خستگی‌اش."
            ),
            "اگر تنشی پیش آمد، بحث را با مهربانی به چند روز بعد موکول کن: «الان حال تو مهم‌تر است، بعداً با هم حرف می‌زنیم.»"
        )
        Phase.AFTER_PERIOD -> PhaseGuide(
            "انرژی تازه، وقت برنامه‌ریزی",
            listOf(
                "یک بیرون رفتن یا ورزش دونفره برنامه‌ریزی کن.",
                "برای حرف‌های مهم و برنامه‌ریزی مشترک زمان خوبی است.",
