            ),
            listOf(
                "پر کردن همه وقتش با برنامه‌های خودت.",
                "نادیده گرفتن پیشنهادهایش."
            ),
            "اگر موضوع حل‌نشده‌ای دارید، این روزها برای گفت‌وگوی آرام و راه‌حل‌محور مناسب‌ترند."
        )
        Phase.MID_CYCLE -> PhaseGuide(
            "نزدیکی و توجه",
            listOf(
                "از او تعریف صادقانه و مشخص کن.",
                "یک قرار عاشقانه یا شام دونفره ترتیب بده.",
                "وقتی باکیفیت و بدون گوشی با هم بگذرانید."
            ),
            listOf(
                "بی‌توجهی به تلاشش برای وقت گذراندن با تو.",
                "مقایسه او با دیگران، حتی به شوخی."
