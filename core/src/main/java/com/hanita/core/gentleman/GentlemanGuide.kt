    fun pillarsFor(status: Status): List<Pillar> = PILLARS.filter { it.fits(status) }

    fun pillar(id: String): Pillar? = PILLARS.firstOrNull { it.id == id }

    /** Today's principle: a different one each day, rotating through every pillar that fits. */
    fun principleOfDay(status: Status, date: LocalDate): Pair<Pillar, Principle> {
        val all = pillarsFor(status).flatMap { p -> p.principles.map { p to it } }
        // Interleave pillars so consecutive days come from different topics.
        val ordered = all.withIndex().sortedBy { (i, item) -> item.first.principles.indexOf(item.second) * 100 + i }.map { it.value }
        return ordered[Math.floorMod(date.toEpochDay(), ordered.size.toLong()).toInt()]
    }

    /** Today's challenge, from a different pillar than today's principle when possible. */
    fun challengeOfDay(status: Status, date: LocalDate): Pair<Pillar, String> {
        val pillars = pillarsFor(status)
        val principlePillar = principleOfDay(status, date).first
        val all = pillars.flatMap { p -> p.challenges.map { p to it } }
            .withIndex().sortedBy { (i, item) -> item.first.challenges.indexOf(item.second) * 100 + i }.map { it.value }
        val start = Math.floorMod(date.toEpochDay() * 7 + 3, all.size.toLong()).toInt()
        for (k in all.indices) {
            val candidate = all[(start + k) % all.size]
            if (candidate.first.id != principlePillar.id) return candidate
        }
        return all[start]
    }

